#!/usr/bin/env python3
# Generates XI.Zone/ZoneRegions.cs: zoneutils::GetCurrentRegion's xi::ZoneId -> REGION_TYPE switch as a table keyed
# by zone id. Zone ids come from data/enums/zone.yaml; the C++ enumerator names are its snake_case keys in
# PascalCase, so both sides are matched with underscores dropped and case folded.
#
# stdlib-only. Deterministic: zone id order.

import re
from pathlib import Path

ZONEUTILS = Path(r"H:\023-FFXI-server\server\src\map\utils\zoneutils.cpp")
ZONE_ENUM = Path(r"H:\023-FFXI-server\server\data\enums\zone.yaml")
ZONE_H = Path(r"H:\023-FFXI-server\server\src\map\zone.h")
OUT = Path(r"H:\023-FFXI-server\csharp\src\XI.Zone\ZoneRegions.cs")


def norm(name):
    return name.replace("_", "").lower()


def main():
    ids = {}
    in_values = False
    for line in ZONE_ENUM.read_text(encoding="utf-8").splitlines():
        if line.startswith("values:"):
            in_values = True
            continue
        m = re.match(r"^  ([a-z0-9_]+):\s+(\d+)", line) if in_values else None
        if m:
            ids[norm(m.group(1))] = int(m.group(2))

    regions = {}
    body = ZONE_H.read_text(encoding="utf-8")
    enum = body[body.index("enum class REGION_TYPE"):]
    enum = enum[:enum.index("};")]
    for m in re.finditer(r"(\w+)\s*=\s*(\d+)", enum):
        regions[m.group(1)] = int(m.group(2))

    src = ZONEUTILS.read_text(encoding="utf-8")
    start = src.index("auto GetCurrentRegion(const xi::ZoneId zoneId) -> REGION_TYPE")
    src = src[start:src.index("return REGION_TYPE::UNKNOWN;", start)]
    table = {}
    pending = []
    for line in src.splitlines():
        m = re.search(r"case xi::ZoneId::(\w+):", line)
        if m:
            key = norm(m.group(1))
            if key not in ids:
                raise SystemExit(f"zone {m.group(1)} not in zone.yaml")
            pending.append(ids[key])
            continue
        m = re.search(r"return REGION_TYPE::(\w+);", line)
        if m:
            for z in pending:
                table[z] = regions[m.group(1)]
            pending = []

    out = [
        "// GENERATED by tools/gen_zone_regions.py from zoneutils::GetCurrentRegion. Do not edit.",
        "",
        "using System.Collections.Generic;",
        "",
        "namespace XI.Zone",
        "{",
        "    public static class ZoneRegions",
        "    {",
        "        public const byte Unknown = 255;",
        "",
        "        private static readonly Dictionary<ushort, byte> regions_ = new Dictionary<ushort, byte>",
        "        {",
    ]
    for z in sorted(table):
        out.append(f"            [{z}] = {table[z]},")
    out += [
        "        };",
        "",
        "        // zoneutils::GetCurrentRegion: REGION_TYPE of a zone, Unknown for one the switch does not list",
        "        public static byte Of(ushort zoneId) => regions_.TryGetValue(zoneId, out var r) ? r : Unknown;",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(table)} zones -> {OUT}")


if __name__ == "__main__":
    main()
