"""Generate an MSVC layout harness for packet structs lifted verbatim from engine source.

    py -3 gen_layout_harness.py <name> <source.cpp|.h> <first-line-marker> <end-line-marker> [outer struct ...]

Copies source text from the line containing <first-line-marker> up to (not including) the line containing
<end-line-marker> into oracle/<name>_harness.cpp, then emits, for every struct in that text:
  BIT  <struct>.<field> mask <hex>   -- each bitfield's bits, found by setting it to all-ones (the compiler places it)
  SIZE <struct> <n>
and for each named outer struct, OFF <struct>.<member> <offset> for every non-bitfield member. Build/run it with
build_layout_harness.bat <name>; the output (<name>_golden.txt) is the authority for hand-written C# offsets.
"""
import re
import sys

name, src, first, end = sys.argv[1:5]
outers = sys.argv[5:]
lines = open(src, encoding="utf-8").read().splitlines()
a = next(i for i, l in enumerate(lines) if first in l)
b = next(i for i, l in enumerate(lines) if i > a and end in l)
text = "\n".join(lines[a:b])

NL = "\\n"
out = [f"// GENERATED by gen_layout_harness.py from {src.replace(chr(92), '/')} -- do not edit",
       "#include <cstdio>", "#include <cstdint>", "#include <cstring>", "#include <cstddef>",
       "using uint8 = uint8_t; using uint16 = uint16_t; using uint32 = uint32_t; using int8 = int8_t;",
       text,
       "template<class T> unsigned long long raw(const T& t){unsigned long long v=0; std::memcpy(&v,&t,sizeof(T)<8?sizeof(T):8); return v;}",
       "int main(){"]

ns = re.search(r"namespace\s+(\w+)", text)
for m in re.finditer(r"^\s*struct\s+(\w+)\s*\n\s*\{(.*?)^\s*\};", text, re.M | re.S):
    sname, body = m.group(1), m.group(2)
    qual = f"{ns.group(1)}::{sname}" if ns and text.index(ns.group(0)) < m.start() and "} // namespace" in text[m.start():] else sname
    out.append(f'  printf("SIZE {sname} %zu{NL}", sizeof({qual}));')
    for f, _ in re.findall(r"^\s*\w+(?:::\w+)?\s+(\w+)\s*:\s*(\d+)\s*;", body, re.M):
        if sname in outers:
            continue  # header id/size bits are written by SetOpcode/SetSize, not by the builder
        out.append(f'  {{ {qual} t{{}}; t.{f} = ~0ull; printf("BIT {sname}.{f} mask %llx{NL}", raw(t)); }}')
    if sname in outers:
        for f in re.findall(r"^\s*[\w:]+\s+(\w+)\s*(?:\[[^\]]*\])?\s*;", body, re.M):
            out.append(f'  printf("OFF {sname}.{f} %zu{NL}", offsetof({qual}, {f}));')
out.append("}")
open(f"{name}_harness.cpp", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {name}_harness.cpp")
