# Generates src/XI.Zone/SjisTable.cs from server/src/common/sjis.h's UnicodeToSjis[65536] (encoding::utf8ToShiftJis):
# the mapped codepoints as (codepoint, sjis) pairs. Run: py -3 csharp\tools\gen_sjis_table.py
import os, re
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(root, 'server', 'src', 'common', 'sjis.h'), encoding='utf-8').read()
body = src[src.index('UnicodeToSjis[65536] = {'):]
body = body[body.index('{') + 1:body.index('};')]
vals = [int(v, 16) for v in re.findall(r'0x[0-9A-Fa-f]+', body)]
assert len(vals) == 65536, len(vals)
pairs = [(cp, v) for cp, v in enumerate(vals) if v != 0 or cp == 0]
out = ['// Generated by tools/gen_sjis_table.py from server/src/common/sjis.h -- do not edit.',
       'namespace XI.Zone', '{', '    internal static class SjisTable', '    {',
       '        // UnicodeToSjis: (codepoint, Shift-JIS) for every mapped codepoint below 0x10000',
       '        internal static readonly ushort[] Pairs =', '        {']
for i in range(0, len(pairs), 8):
    out.append('            ' + ' '.join('0x%04X, 0x%04X,' % p for p in pairs[i:i + 8]))
out += ['        };', '    }', '}', '']
dst = os.path.join(root, 'csharp', 'src', 'XI.Zone', 'SjisTable.cs')
open(dst, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
print('wrote', dst, len(pairs), 'pairs')
