    // struct CharZone { uint32 charId; xi::ZoneId destinationZoneId; }
    public sealed class CharZone : IIpcMessage
    {
        public MessageType Type => MessageType.CharZone;
        public uint CharId;
        public ZoneId DestinationZoneId;

        public CharZone() { }
        public CharZone(uint charId, ZoneId destinationZoneId) { CharId = charId; DestinationZoneId = destinationZoneId; }

        public void WriteBody(CborWriter w)
        {
            w.WriteStartMap(2);
            w.WriteTextString("charId");
            w.WriteUInt32(CharId);
            w.WriteTextString("destinationZoneId");
            w.WriteUInt32((uint)DestinationZoneId);
            w.WriteEndMap();
        }

        public void ReadBody(CborReader r)
        {
            r.ReadStartMap();
            r.ReadTextString(); CharId = r.ReadUInt32();
            r.ReadTextString(); DestinationZoneId = (ZoneId)r.ReadUInt32();
            r.ReadEndMap();
        }
    }

