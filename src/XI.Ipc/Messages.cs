    // std::map -> CBOR definite-length map (major-5), insertion == std::map key order.
    public sealed class GMCallRequest : IIpcMessage
    {
        public MessageType Type => MessageType.GMCallRequest;
        public uint CallId;
        public uint CharId;
        public string CharName = "";
        public uint AccId;
        public ZoneId ZoneId;
        public float PosX;
        public float PosY;
        public float PosZ;
        public string Message = "";
        public System.Collections.Generic.Dictionary<string, string> Parameters = new();

        public GMCallRequest() { }

        public void WriteBody(CborWriter w)
        {
            w.WriteStartMap(10);
            w.WriteTextString("callId");
            w.WriteUInt32(CallId);
            w.WriteTextString("charId");
            w.WriteUInt32(CharId);
            w.WriteTextString("charName");
            CborRaw.WriteText(w, CharName);
            w.WriteTextString("accId");
            w.WriteUInt32(AccId);
            w.WriteTextString("zoneId");
            w.WriteUInt32((uint)ZoneId);
            w.WriteTextString("posX");
            w.WriteSingle(PosX);
            w.WriteTextString("posY");
            w.WriteSingle(PosY);
            w.WriteTextString("posZ");
            w.WriteSingle(PosZ);
            w.WriteTextString("message");
            CborRaw.WriteText(w, Message);
            w.WriteTextString("parameters");
            w.WriteStartMap(Parameters.Count);
            foreach (var kv in Parameters)
            {
                w.WriteTextString(kv.Key);
                w.WriteTextString(kv.Value);
            }
            w.WriteEndMap();
            w.WriteEndMap();
        }

        public void ReadBody(CborReader r)
        {
            r.ReadStartMap();
            r.ReadTextString(); CallId = r.ReadUInt32();
            r.ReadTextString(); CharId = r.ReadUInt32();
            r.ReadTextString(); CharName = CborRaw.ReadText(r);
            r.ReadTextString(); AccId = r.ReadUInt32();
            r.ReadTextString(); ZoneId = (ZoneId)r.ReadUInt32();
            r.ReadTextString(); PosX = r.ReadSingle();
            r.ReadTextString(); PosY = r.ReadSingle();
            r.ReadTextString(); PosZ = r.ReadSingle();
            r.ReadTextString(); Message = CborRaw.ReadText(r);
            r.ReadTextString();
            int n = r.ReadStartMap().Value;
            Parameters = new System.Collections.Generic.Dictionary<string, string>(n);
            for (int i = 0; i < n; i++)
            {
                string k = r.ReadTextString();
                string v = r.ReadTextString();
                Parameters[k] = v;
            }
            r.ReadEndMap();
            r.ReadEndMap();
        }
    }

    // struct GMCallResponse { uint32 callId; uint32 charId; std::string message; }
    public sealed class GMCallResponse : IIpcMessage
    {
        public MessageType Type => MessageType.GMCallResponse;
        public uint CallId;
        public uint CharId;
        public string Message = "";

        public GMCallResponse() { }

