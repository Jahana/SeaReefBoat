#!/usr/bin/env python3
# Generates the C# PacketC2S / PacketS2C id enums (src/map/enums/packet_{c2s,s2c}.h) into
# XI.Map/PacketIds.cs. These are HAND-AUTHORED literal enums (magic_enum is not vendored and the
# iron rule covers only compiler-derived sizeof/offsetof/crypto bytes), so the engine .h is the
# source of truth; we generate rather than hand-copy the ~285 members, and tests/XI.Verify.Map
# re-parses the same .h with an INDEPENDENT C# implementation to prove faithfulness + catch drift.
#
# stdlib-only (runs offline). Deterministic: preserves engine declaration order.

import re
import sys
from pathlib import Path

SRC = Path(r"H:\023-FFXI-server\server")
ENUMS = [
    ("PacketC2S", SRC / "src/map/enums/packet_c2s.h"),
    ("PacketS2C", SRC / "src/map/enums/packet_s2c.h"),
]
OUT = Path(r"H:\023-FFXI-server\csharp\src\XI.Map\PacketIds.cs")

MEMBER_RE = re.compile(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0[xX][0-9A-Fa-f]+|\d+)\s*,?\s*$')
IMPLICIT_RE = re.compile(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s*,\s*$')


def strip_block_comments(text):
    # Remove /* ... */ (the GPL header) so they can never shadow a member line.
    return re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)


def parse_enum(text, name):
    """Return [(member, value_int), ...] for `enum class <name> : uint16_t { ... }`, bounded at
    the enum's own matching braces so the trailing magic_enum enum_range struct is excluded."""
    m = re.search(r"enum\s+class\s+" + re.escape(name) + r"\s*:\s*uint16_t", text)
    if not m:
        sys.exit(f"enum class {name} : uint16_t not found")
    i = text.index("{", m.end())
    depth = 0
    end = None
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                end = j
                break
    if end is None:
        sys.exit(f"unbalanced braces in enum {name}")
    body = text[i + 1:end]

    members = []
    prev = -1
    for raw in body.splitlines():
        line = raw.split("//", 1)[0].rstrip()
        if not line.strip():
            continue
        mm = MEMBER_RE.match(line)
        if mm:
            val = int(mm.group(2), 0)
            members.append((mm.group(1), val))
            prev = val
            continue
        im = IMPLICIT_RE.match(line)
        if im:  # defensive: engine has none today, but match C++ prev+1 semantics
            val = prev + 1
            members.append((im.group(1), val))
            prev = val
    return members


def main():
    text_c2s = strip_block_comments(ENUMS[0][1].read_text(encoding="utf-8"))
    text_s2c = strip_block_comments(ENUMS[1][1].read_text(encoding="utf-8"))

    c2s = parse_enum(text_c2s, "PacketC2S")
    s2c = parse_enum(text_s2c, "PacketS2C")

    # Guard: a parse that yields (near-)empty means the regex or bounding broke -- fail loudly
    # rather than emit empty enums that the parity gate would then vacuously pass.
    if len(c2s) < 100 or len(s2c) < 100:
        sys.exit(f"suspiciously small parse: PacketC2S={len(c2s)} PacketS2C={len(s2c)}")

    def emit(name, members):
        lines = [f"    public enum {name} : ushort"]
        lines.append("    {")
        for mem, val in members:
            lines.append(f"        {mem} = 0x{val:X},")
        lines.append("    }")
        return "\n".join(lines)

    header = (
        "// GENERATED by csharp/tools/gen_packet_ids.py from the engine's "
        "src/map/enums/packet_{c2s,s2c}.h -- DO NOT hand-edit.\n"
        "// Regenerate: `py -3 csharp/tools/gen_packet_ids.py`. Parity (name->value) is asserted by\n"
        "// tests/XI.Verify.Map, which independently re-parses the same .h. Values are the engine's "
        "own\n"
        "// hand-authored uint16_t literals (magic_enum is not vendored; the iron rule covers only\n"
        "// compiler-derived sizeof/offsetof/crypto bytes, not enum literals).\n"
    )

    body = "namespace XI.Map\n{\n" + header + "\n" + emit("PacketC2S", c2s) + "\n\n" + emit("PacketS2C", s2c) + "\n}\n"
    OUT.write_text(body, encoding="utf-8", newline="\n")

    # Duplicate-name guard (a C# enum member name must be unique; the engine keeps them unique).
    for name, members in (("PacketC2S", c2s), ("PacketS2C", s2c)):
        seen = set()
        for mem, _ in members:
            if mem in seen:
                sys.exit(f"duplicate member {mem} in {name}")
            seen.add(mem)

    print(f"wrote {OUT}  (PacketC2S={len(c2s)} members, PacketS2C={len(s2c)} members)")


if __name__ == "__main__":
    main()
