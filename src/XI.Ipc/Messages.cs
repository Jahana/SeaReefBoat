// IPC message DTOs for the cross-process (map<->world<->login) channel.
//
// Wire format (mirrors src/common/ipc.h toBytesWithHeader/fromBytesWithHeader):
//   [ 1 raw byte = MessageType ][ glaze CBOR payload ]
// The CBOR payload is the struct serialized by glz::write_cbor. Because NO ipc::
// struct has a glz::meta specialization (verified 2026-10-15: all glz::meta hits are
// in the map/data yaml layer), glaze emits a DEFINITE-LENGTH CBOR MAP keyed by the
// member names, in C++ declaration order. The enum members are integers (glaze writes
// enum underlying values as CBOR ints). uint8 = CBOR uint; int32 = CBOR negint when <0.
//
// Field names + order here are copied verbatim from src/common/ipc_structs.h so the
// generated map keys match byte-for-byte.
using System.Formats.Cbor;

namespace XI.Ipc
{
    public interface IIpcMessage
    {
        MessageType Type { get; }
        void WriteBody(CborWriter w);
        void ReadBody(CborReader r);
    }

    // xi::ZoneId: generated by tools/codegen/enum_codegen.py from data/enums/zone.yaml,
    // whose meta.cpp.underlying is uint16_t (verified 2026-10-15). glaze serializes an enum as
    // its underlying integer, so on the wire it is a CBOR major-type-0 int == WriteUInt32 here.
    public enum ZoneId : ushort
    {
        Unknown = 0,
    }

