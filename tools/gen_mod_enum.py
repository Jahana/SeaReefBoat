#!/usr/bin/env python3
# Generates the C# Mod enum (xi::Mod, data/enums/mod.yaml) into XI.Zone/Mod.cs. The yaml is the source the C++
# header and scripts/enum/mod.codegen.lua are generated from; names keep the C++ SCREAMING case so xi::Mod::X and
# xi.mod.X grep straight to Mod.X.
#
# stdlib-only. Deterministic: preserves yaml declaration order.

import re
from pathlib import Path

SRC = Path(r"H:\023-FFXI-server\server\data\enums\mod.yaml")
OUT = Path(r"H:\023-FFXI-server\csharp\src\XI.Zone\Mod.cs")

MEMBER_RE = re.compile(r'^  ([a-z0-9_]+):\s+(\d+)\s*(?:#\s*(.*))?$')


def main():
    members = []
    in_values = False
    for line in SRC.read_text(encoding="utf-8").splitlines():
        if line.startswith("values:"):
            in_values = True
            continue
        if not in_values:
            continue
        m = MEMBER_RE.match(line)
        if m:
            members.append((m.group(1).upper(), int(m.group(2)), (m.group(3) or "").strip()))

    top = max(v for _, v, _ in members)
    width = max(len(n) for n, _, _ in members)
    out = [
        "// GENERATED by tools/gen_mod_enum.py from data/enums/mod.yaml. Do not edit.",
        "",
        "namespace XI.Zone",
        "{",
        "    // xi::Mod: the codes for every modifier an entity can carry",
        "    public enum Mod : ushort",
        "    {",
    ]
    for name, value, comment in members:
        line = f"        {name.ljust(width)} = {value},"
        if comment:
            line += f" // {comment}"
        out.append(line)
    out += [
        "    }",
        "",
        "    public static class Mods",
        "    {",
        f"        // one past the highest Mod: the size of a per-entity modifier array",
        f"        public const int Count = {top + 1};",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(members)} mods, highest {top} -> {OUT}")


if __name__ == "__main__":
    main()
